// docs/ERRORS.md を examples/bad/ の見本から作る。--check のときは、今のファイルと違えば失敗する（テストが使う）
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { runSource, CODES, RETIRED } from '../src/index.js';

const badDir = new URL('../examples/bad/', import.meta.url);
const target = new URL('../docs/ERRORS.md', import.meta.url);

export function render() {
  const samples = new Map();
  for (const f of readdirSync(badDir).filter((x) => x.endsWith('.ak')).sort()) {
    const src = readFileSync(new URL(f, badDir), 'utf8');
    const code = src.match(/^# expect: (\w+)/)[1];
    if (!samples.has(code)) samples.set(code, { f, src: src.replace(/^# expect: .*\n/, '').replace(/^# grant: (.*)\n/m, '# run with --allow-read $1\n'), d: runSource(src, { grants: { folder: src.match(/^# grant: (.+)$/m)?.[1] }, file: new URL(f, badDir).pathname }).diagnostics[0] });
  }
  let md = '# エラー番号の一覧（Akashi error codes）\n\n';
  md += '<!-- generated by scripts/gen-errors.mjs from examples/bad/. Do not edit by hand. -->\n\n';
  md += '番号の意味は変えません（AI が覚えて直せるように）。`E` は動かす前の検査（`akashi check`）、`R` は動かしたときに見つかったものです。\n';
  md += 'どのエラーにも番号（`code`）・場所（`line`・`col`）・説明（`message`）・直し方（`fix`）が付きます。`--json` で同じものを JSON で読めます。\n';
  md += 'エラー文は英語です（AI に渡す文なので、学習データの多い言葉で短く書いています）。直し方の読み方は [やり方集](howto.md#エラーを直す) を見てください。\n';
  md += 'この一覧は `examples/bad/` の見本から作っています。下の message と fix は、見本を実際に動かした結果です。\n\n';
  md += '| 番号 | 意味 |\n| --- | --- |\n';
  for (const [code, title] of Object.entries(CODES)) md += `| [${code}](#${code.toLowerCase()}) | ${title} |\n`;
  for (const [code, title] of Object.entries(CODES)) {
    md += `\n## ${code}\n\n${title}.\n`;
    if (RETIRED.includes(code)) { md += '\nこの番号はもう出しません。番号は使い回しません。\n'; continue; }
    const s = samples.get(code);
    if (!s) continue;
    md += `\n\`\`\`\n${s.src.trimEnd()}\n\`\`\`\n\n`;
    md += `- message: ${s.d.message}\n- fix: ${s.d.fix}\n`;
  }
  return md;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const md = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== md) { console.error('docs/ERRORS.md is stale: run node scripts/gen-errors.mjs'); process.exit(1); }
  } else {
    writeFileSync(target, md);
    console.log('wrote docs/ERRORS.md');
  }
}
